"""Generate Codex and Claude Code agents from canonical role definitions."""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "agents" / "roles"
CODEX_DIR = ROOT / ".codex" / "agents"
CLAUDE_DIR = ROOT / ".claude" / "agents"
SHARED_PATH = SOURCE_DIR / "_shared.md"
ROLE_NAMES = (
    "product-owner",
    "solution-architect",
    "developer",
    "code-reviewer",
    "tester",
)
ROLE_BOUNDARIES = {
    "product-owner": "Do not modify application code",
    "solution-architect": "Do not implement application code",
    "developer": "Do not merge or deploy",
    "code-reviewer": "Do not modify implementation files",
    "tester": "Do not create or edit application code, test code, configuration, snapshots,",
}
GENERATED_NOTICE = "Generated by scripts/sync_agents.py; edit agents/roles instead."


@dataclass(frozen=True)
class Role:
    name: str
    description: str
    instructions: str


def parse_source(path: Path, shared: str) -> Role:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError(f"{path}: expected YAML frontmatter")
    raw_header, body = text[4:].split("\n---\n", 1)
    metadata: dict[str, str] = {}
    for line in raw_header.splitlines():
        if ":" not in line:
            raise ValueError(f"{path}: invalid frontmatter line: {line!r}")
        key, value = line.split(":", 1)
        metadata[key.strip()] = value.strip()
    if set(metadata) != {"name", "description"}:
        raise ValueError(f"{path}: frontmatter must contain name and description only")
    if metadata["name"] != path.stem:
        raise ValueError(f"{path}: name must match filename")
    description = metadata["description"]
    if "explicitly requests" not in description or "never invoke automatically" not in description:
        raise ValueError(f"{path}: description must enforce explicit-only invocation")
    instructions = f"{shared.rstrip()}\n\n{body.strip()}\n"
    required_phrases = (
        "Never invoke the next role",
        "Humans approve requirements",
        "GitHub",
        "Do not merge",
    )
    for phrase in required_phrases:
        if phrase not in instructions:
            raise ValueError(f"{path}: missing shared rule {phrase!r}")
    boundary = ROLE_BOUNDARIES[metadata["name"]]
    if boundary not in instructions:
        raise ValueError(f"{path}: missing role boundary {boundary!r}")
    return Role(metadata["name"], description, instructions)


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_codex(role: Role) -> str:
    if '"""' in role.instructions:
        raise ValueError(f"{role.name}: instructions cannot contain TOML triple quotes")
    return (
        f"# {GENERATED_NOTICE}\n"
        f"name = {toml_string(role.name)}\n"
        f"description = {toml_string(role.description)}\n"
        'developer_instructions = """\n'
        f"{role.instructions}"
        '"""\n'
    )


def render_claude(role: Role) -> str:
    denied = "Agent"
    if role.name in ("tester", "code-reviewer"):
        denied += ", Write, Edit, NotebookEdit"
    return (
        "---\n"
        f"name: {role.name}\n"
        f"description: {json.dumps(role.description, ensure_ascii=False)}\n"
        f"disallowedTools: {denied}\n"
        "---\n"
        f"<!-- {GENERATED_NOTICE} -->\n\n"
        f"{role.instructions}"
    )


def validate_codex(content: str, role: Role) -> None:
    parsed = tomllib.loads(content)
    expected = {
        "name": role.name,
        "description": role.description,
        "developer_instructions": role.instructions,
    }
    if parsed != expected:
        raise ValueError(f"{role.name}: generated Codex TOML does not match canonical source")


def validate_claude(content: str, role: Role) -> None:
    if not content.startswith("---\n") or "\n---\n" not in content[4:]:
        raise ValueError(f"{role.name}: invalid Claude frontmatter")
    raw_header, body = content[4:].split("\n---\n", 1)
    fields: dict[str, str] = {}
    for line in raw_header.splitlines():
        key, value = line.split(":", 1)
        fields[key.strip()] = value.strip()
    if fields.get("name") != role.name:
        raise ValueError(f"{role.name}: Claude name mismatch")
    if json.loads(fields.get("description", '""')) != role.description:
        raise ValueError(f"{role.name}: Claude description mismatch")
    if set(fields) != {"name", "description", "disallowedTools"}:
        raise ValueError(f"{role.name}: unexpected Claude frontmatter fields")
    denied = {"Agent"}
    if role.name in ("tester", "code-reviewer"):
        denied.update(("Write", "Edit", "NotebookEdit"))
    actual_denied = {item.strip() for item in fields.get("disallowedTools", "").split(",")}
    if actual_denied != denied:
        raise ValueError(f"{role.name}: Claude delegation/editing restrictions mismatch")
    expected_body = f"<!-- {GENERATED_NOTICE} -->\n\n{role.instructions}"
    if body != expected_body:
        raise ValueError(f"{role.name}: Claude instructions do not match canonical source")


def expected_outputs(tool: str = "all") -> dict[Path, str]:
    shared = SHARED_PATH.read_text(encoding="utf-8")
    outputs: dict[Path, str] = {}
    for name in ROLE_NAMES:
        role = parse_source(SOURCE_DIR / f"{name}.md", shared)
        if tool in ("all", "codex"):
            codex = render_codex(role)
            validate_codex(codex, role)
            outputs[CODEX_DIR / f"{name}.toml"] = codex
        if tool in ("all", "claude"):
            claude = render_claude(role)
            validate_claude(claude, role)
            outputs[CLAUDE_DIR / f"{name}.md"] = claude
    return outputs


def sync(check: bool, tool: str = "all") -> int:
    outputs = expected_outputs(tool)
    expected_paths = set(outputs)
    stale: list[Path] = []
    for output_dir, pattern in ((CODEX_DIR, "*.toml"), (CLAUDE_DIR, "*.md")):
        if tool == "codex" and output_dir == CLAUDE_DIR:
            continue
        if tool == "claude" and output_dir == CODEX_DIR:
            continue
        if output_dir.exists():
            unexpected = set(output_dir.glob(pattern)) - expected_paths
            if unexpected:
                names = ", ".join(str(path.relative_to(ROOT)) for path in sorted(unexpected))
                raise ValueError(f"unexpected generated agent files: {names}")
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    if stale and check:
        for path in stale:
            print(f"OUT OF DATE: {path.relative_to(ROOT)}")
        print(f"Run: uv run --no-project python scripts/sync_agents.py --tool {tool}")
        return 1
    action = "checked" if check else "synchronized"
    print(f"Agent definitions {action} ({tool}): {len(ROLE_NAMES)} roles, {len(outputs)} generated files.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated files drift")
    parser.add_argument("--tool", choices=("all", "codex", "claude"), default="all",
                        help="generate/check only the selected tool (default: all)")
    args = parser.parse_args()
    try:
        return sync(args.check, args.tool)
    except (OSError, ValueError, tomllib.TOMLDecodeError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
